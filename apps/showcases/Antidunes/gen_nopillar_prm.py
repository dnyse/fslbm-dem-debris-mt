#!/usr/bin/env python3
"""Generate the 'NO PILLARS, PID ON, 100000 steps' hopper prms (rods and spheres) from the existing pillar prms.

[Claude, 2026-09-21] Purpose: the PID-on cylinder run that crashed (4252146 -> 4252462, sealed pore at ~29k) had two cylindrical pillars
(X=384, R=12) in the channel. Does the crash need the pillars/the jam, or do rods crash in an OPEN channel just the same? The sphere twin
(same channel, same PID, same block of debris, no pillars) is the shape control. Both write the new flow-rate columns of the
ClogMeasurement evaluator (Q and wet area of the y-z planes at x=336 and x=432, i.e. where the pre-/post-pillar planes were).
Only these things differ from the source prms: CylinderPillars block and both BodyBC pillar lines removed, timesteps 100000, snapshots
every 10000, ClogMeasurement.flowRateEnabled true (pillar probe pair dropped), header; rods: sanity/dense scan windows extended, sweep
every 10 steps.
"""
import re, pathlib, sys
D = pathlib.Path(__file__).parent / "prms"

def strip_block(t, name):
    m = re.search(r"^%s\s*\n\{" % name, t, flags=re.M)
    assert m, name
    i = m.start(); depth = 0; j = t.index("{", i)
    k = j
    while True:
        if t[k] == "{": depth += 1
        elif t[k] == "}":
            depth -= 1
            if depth == 0: break
        k += 1
    return t[:i] + t[k+1:].lstrip("\n")

def common(t):
    t = strip_block(t, "CylinderPillars")
    n0 = len(t)
    t = re.sub(r"^\s*BodyBC \{ shape Cylinder;[^\n]*\n", "", t, flags=re.M)
    assert n0 - len(t) > 100, "BodyBC pillar lines not removed"
    t = re.sub(r"^\s*//\s*Fluid-blocking counterparts of the CylinderPillars[^\n]*\n", "   // (no pillars in this run)\n", t, flags=re.M)
    t, n = re.subn(r"timesteps\s+\d+;", "timesteps         100000;", t, count=1); assert n == 1
    t, n = re.subn(r"snapshotFrequency\s+\d+;", "snapshotFrequency             10000;", t, count=1); assert n == 1
    t, n = re.subn(r"\n\s*pillarUpstreamPos[^\n]*\n\s*pillarDownstreamPos[^\n]*", "", t); assert n == 1
    t, n = re.subn(r"(probeHalfWidthXY\s+\d+;)", r"\1\n      flowRateEnabled   true;   // NEW: volumetric flow rate Q + wet area of the y-z plane at x=336 (pre) and x=432 (post) -> clogUpstream/DownstreamFlowRate, ...WetArea", t, count=1); assert n == 1
    return t

# ---- rods ----
src = D / "hopper_clog_cyl_frontblock_pidon_2node_gjk_sanity_18k_gas.prm"
t = common(src.read_text())
for key in ("denseNanScanToStep", "fluidSanityToStep"):
    t, n = re.subn(r"(%s\s+)\d+;" % key, r"\g<1>100000;", t); assert n == 1, key
t, n = re.subn(r"(fluidSanityEveryNSteps\s+)\d+;", r"\g<1>10;", t); assert n == 1
t, n = re.subn(r"(fluidSanityStatsEveryNSteps\s+)\d+;", r"\g<1>500;", t); assert n == 1
hdr = """// hopper_clog_cyl_nopillars_pidon_2node_100k_gas.prm   (GENERATED by gen_nopillar_prm.py from hopper_clog_cyl_frontblock_pidon_2node_gjk_sanity_18k_gas.prm -- edit the script)
// [Claude, 2026-09-21] NO PILLARS. The PID-ON rod hopper of 4252146/4252462 (406 rods r=3 L=18, block X 169..371, GJK/EPA-only contacts, PID target 0.04, fluid sanity sweep) with the two
// pillars REMOVED (CylinderPillars + BodyBC), 100000 steps, checkpoints every 10000. Question: do the rods still crash in an open channel (sealed pore / bundle channel), or is the jam at the pillars needed?
// Flow-rate planes (ClogMeasurement.flowRateEnabled): x=336 and x=432 (the former pre-/post-pillar positions); the block starts at x 169..371, so the upstream plane crosses rods early on (tests the evaluator with bodies in the flow).
// Diagnostics as in the sanity run (dense NaN scan + sweep, sweep every 10 steps instead of every step to save time). Source prm header follows.
"""
(D / "hopper_clog_cyl_nopillars_pidon_2node_100k_gas.prm").write_text(hdr + t)

# ---- spheres ----
src = D / "hopper_clog_pidon_2node_frontblock_gas.prm"
t = common(src.read_text())
hdr = """// hopper_clog_nopillars_pidon_2node_100k_gas.prm   (GENERATED by gen_nopillar_prm.py from hopper_clog_pidon_2node_frontblock_gas.prm -- edit the script)
// [Claude, 2026-09-21] NO PILLARS, SPHERE CONTROL for hopper_clog_cyl_nopillars_pidon_2node_100k_gas.prm: the sphere front-block hopper of 4248723 (1015 spheres, PID on, target 0.04) with the pillars
// REMOVED, 100000 steps, checkpoints every 10000, flow-rate planes at x=336 / x=432. No extra fluid diagnostics (cost per step as in 4248723: ~0.1 s). Source prm header follows.
"""
(D / "hopper_clog_nopillars_pidon_2node_100k_gas.prm").write_text(hdr + t)
print("ok")
