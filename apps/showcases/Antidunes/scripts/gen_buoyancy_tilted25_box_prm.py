#!/usr/bin/env python3
"""Add initialTiltAngleDeg 25 to a buoyancy_compare box prm's FloatingBox line (both mem and analytic arms, so the
two methods start from an IDENTICAL initial condition and stay directly comparable).

Why: the R1 box at upright (0 deg) sits on a mapping tie -- its face planes pass exactly through cell centres, and
depending on which way the tie resolves, the mapped bottom layer can end up flush on the floor with no fluid cell
underneath, starving MEM-only buoyancy of the pressure it needs from below. A 25 deg initial tilt breaks every
face-alignment tie at once (tested on R1/box/MEM: the box rises 41.5 -> 56.1 over 2590 steps). The analytic arm never
had the tie problem, but is tilted too so both arms start from the same box orientation and stay comparable.

usage: gen_buoyancy_tilted25_box_prm.py   (no args; regenerates all 6 from prms/buoyancy_compare_box_r{1,2,4}_{mem,analytic}_gas.prm)
"""
import pathlib, re
D = pathlib.Path(__file__).parent / "prms"
for R in (1, 2, 4):
    for method in ("mem", "analytic"):
        src = D / f"buoyancy_compare_box_r{R}_{method}_gas.prm"
        t = src.read_text()
        t2, n = re.subn(r"(FloatingBox \{ position <[^>]*>; halfExtents <[^>]*>; densityRatio [^;]*; settlingSteps [^;]*;) \}",
                        r"\1 initialTiltAngleDeg 25; }", t, count=1)
        assert n == 1, src
        hdr = (f"// buoyancy_compare_box_r{R}_{method}_tilted25_gas.prm -- GENERATED by gen_buoyancy_tilted25_box_prm.py\n"
               f"// from {src.name} (edit that file or the script): identical except\n// initialTiltAngleDeg 25 about world Y on the FloatingBox.\n")
        out = D / f"buoyancy_compare_box_r{R}_{method}_tilted25_gas.prm"
        out.write_text(hdr + t2)
        print("wrote", out.name)
