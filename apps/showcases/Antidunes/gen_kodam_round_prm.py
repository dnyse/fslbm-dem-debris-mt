#!/usr/bin/env python3
"""[Claude, 2026-10-03] Kodam et al. (2010b, Sec. 3.3) packing test with a ROUND container and one-by-one release,
as close to the experiment as DropTest allows (author's request: "run one that mimics kodams experiment").

Base: prms/DropTest_kodam_packing_gas.prm (gen_kodam_packing_prm.py; square area-matched container, waves of 9). Kept
from it: cylinders R 4, L 5.3 (1 LU = 1 mm: Kodam's 8.0 mm x 5.3 mm), friction 0.5, restitution 0.85, gravity
2.137e-5 LU/step^2 (real gravity for 1 LU = 1 mm at dt = sqrt(2.137e-5 * 1e-3 / 9.81) = 4.67e-5 s), contact detection
(closed form with GJK/EPA fallback), 20 DEM sub-steps.

Changes towards the experiment:
 - Round container of 50.6 mm inner diameter: ContainerCylinders block (vertical CylindricalBoundary in containment
   mode, Utility.h createContainerCylinder; tests: ContactDetectionTest testCylinderVerticalContainer). Domain 52 x 52 x
   160 around it (the box walls stay 0.7 mm outside the circle and are never reached).
 - One cylinder at a time, from rest, random position at z = 125 (container top 130), random orientation. Interval 430
   steps = 0.020 s (50 particles/s). Kodam released the next particle once the previous one was at rest (< 1 s) and cites
   Macrae & Gray (1961) / Zhang et al. (2001): drop rates below 1000 particles/s do not change the final packing
   fraction; a strict rest-to-rest schedule would need ~5M steps.
 - A cylinder falls only 0.5 g t^2 = 2 mm in 430 steps, so a new spawn point keeps >= 10.5 mm horizontal distance from
   the previous three (circumscribed diameter 9.6 mm).
 - Settling tail 20000 steps (0.93 s) after the last release.
 - The earlier one-by-one attempt (gen_kodam_packing_prm.py docstring: 250 -> 193 particles) predates the
   SyncNextNeighbors fix of 2026-10-01; the randomised 250-floater drop tests since then release delayed floaters
   without loss.
Usage: python3 gen_kodam_round_prm.py   ->  prms/DropTest_kodam_round_gas.prm
"""
import math
import re

import numpy as np

SEED = 20261003
N = 250
R, L = 4.0, 5.3
RC = 25.3                      # container radius (50.6 mm diameter)
CX = CY = 26.0                 # container axis in the 52 x 52 domain
Z_SPAWN = 125.0
INTERVAL = 430                 # steps between releases
TAIL = 20000
R_CIRC = math.sqrt(R * R + (0.5 * L) ** 2)      # 4.80, circumscribed radius
R_SPAWN = RC - R_CIRC - 0.5                      # spawn centres stay >= 0.5 mm from the wall
MIN_SEP = 10.5                                   # horizontal distance to the previous 3 spawns

BASE = "prms/DropTest_kodam_packing_gas.prm"
OUT = "prms/DropTest_kodam_round_gas.prm"


def main():
    rng = np.random.default_rng(SEED)
    s = open(BASE).read()
    pts = []
    lines = []
    for k in range(N):
        while True:
            r = R_SPAWN * math.sqrt(rng.uniform())
            th = rng.uniform(0, 2 * math.pi)
            x, y = CX + r * math.cos(th), CY + r * math.sin(th)
            if all(math.hypot(x - px, y - py) >= MIN_SEP for px, py in pts[-3:]):
                break
        pts.append((x, y))
        a = rng.standard_normal(3)
        a /= np.linalg.norm(a)
        st = k * INTERVAL
        tail = f"densityRatio 1.0; settlingSteps {st};" + (" startInactive true;" if st > 0 else "")
        lines.append(f"   FloatingCylinder {{ position < {x:.4f}, {y:.4f}, {Z_SPAWN:.1f} >; radius {R:g}; length {L:g}; "
                     f"axis < {a[0]:.6f}, {a[1]:.6f}, {a[2]:.6f} >; {tail} }}")
    a0 = s.index("\nFloatingCylinders")
    a1 = s.index("\n}", a0) + 2
    s = s[:a0] + "\nFloatingCylinders\n{\n" + "\n".join(lines) + "\n}\n" + s[a1:]
    last = (N - 1) * INTERVAL
    s, n1 = re.subn(r"(\n\s*timesteps\s+)\d+;[^\n]*", rf"\g<1>{last + TAIL};  // last release {last} + {TAIL}", s, count=1)
    s, n2 = re.subn(r"(\n\s*domainSize\s+)<[^>]*>;", r"\1<52, 52, 160>;", s, count=1)
    s, n3 = re.subn(r"(\n\s*cellsPerBlock\s+)<[^>]*>;[^\n]*", r"\1< 13, 13, 160 >;  // 4 x 4 x 1 = 16 processes", s, count=1)
    marker = "// No Pillars / CylinderPillars / ArchTunnels"
    assert n1 == n2 == n3 == 1 and marker in s
    s = s.replace(marker, f"ContainerCylinders\n{{\n   ContainerCylinder {{ center < {CX:g}, {CY:g}, 80 >; radius {RC:g}; }}"
                          f"  // Kodam's 50.6 mm container\n}}\n\n" + marker, 1)
    hdr = (f"// [Claude, 2026-10-03] GENERATED by gen_kodam_round_prm.py (seed {SEED}) -- Kodam packing test with a round\n"
           f"// container and one-by-one release; see the generator's docstring for every change relative to {BASE}.\n")
    open(OUT, "w").write(hdr + s)
    seps = [math.hypot(pts[i][0] - pts[j][0], pts[i][1] - pts[j][1]) for i in range(N) for j in range(max(0, i - 3), i)]
    print(f"{OUT}: {N} cylinders, last release {last}, timesteps {last + TAIL}, min sep to previous 3 = {min(seps):.2f}, "
          f"max spawn radius = {max(math.hypot(x - CX, y - CY) for x, y in pts):.2f} (limit {R_SPAWN:.2f})")


if __name__ == "__main__":
    main()
