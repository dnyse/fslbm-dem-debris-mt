#!/usr/bin/env python3
"""Pinned-sphere RESOLUTION scan (THESIS_PLAN.md 1a, 2026-09-28): the same physical problem at R=1,2,4 (domain, sphere radius 8R and
liquid depth scaled by R, true g_SI=9.81 -> g_LU ~ R^-3, cellsPerBlock fixed), derived from prms/buoyancy_compare_sphere_r{R}_mem_gas.prm.
A FULLY PINNED sphere at nominal 0.75 submerged; mean F_hydro_z vs rho*g*V_sub tells whether the ~0.3-cell pressure-zero offset is a
fixed number of CELLS (first-order scheme, as Bogner's FSK rule) or shrinks with dx.
Generates prms/pinres_sphere_R{R}_gas.prm and jobs/run_{72|576}_pinres_sphere_R{R}.sbatch."""
import re, numpy as np
AVG_D = {1: 8.001943, 2: 16.003887, 4: 32.007773}   # avgParticleDiameter [cells] of the R1/R2/R4 beds (8R; R1 value from the clog prm override)
FACTOR = 6 + 4.1393                                 # liquidHeightFactor + floorHeightFactor (no solid floor: T/B walls only)
STEPS = {1: 12000, 2: 24000, 4: 48000}
EVAL = {1: 250, 2: 500, 4: 1000}
def zc_for(R, f=0.75):
    r = 8.0*R; wl = FACTOR*AVG_D[R]
    lo, hi = wl - r, wl + r
    for _ in range(80):
        m = 0.5*(lo+hi); h = np.clip(wl-(m-r), 0, 2*r); fr = h*h*(3*r-h)*np.pi/3/(4/3*np.pi*r**3)
        lo, hi = (m, hi) if fr > f else (lo, m)
    return round(0.5*(lo+hi), 3), wl
def prm(R):
    t = open(f"prms/buoyancy_compare_sphere_r{R}_mem_gas.prm", encoding="utf-8").read()
    zc, wl = zc_for(R); dom = t and re.search(r"domainSize\s+<\s*(\d+),\s*(\d+),\s*(\d+)\s*>", t); X, Y = int(dom.group(1)), int(dom.group(2))
    T = STEPS[R]; w0, w1 = T - 2000*R, T - 1
    def rep(pat, new, flags=0):
        nonlocal t; n = len(re.findall(pat, t, flags)); assert n == 1, (pat, n); t = re.sub(pat, new, t, flags=flags)
    rep(r"   timesteps\s+\d+;", f"   timesteps         {T};")
    rep(r"   FloatingSphere \{[^}]*\}", f"   FloatingSphere {{ position < {X//2}, {Y//2}, {zc} >; radius {8*R}; densityRatio 0.5; settlingSteps 0; pinPosition true; pinAxes < 1, 1, 1 >; pinRotation true; }}")
    rep(r"evaluationFrequency\s+\d+;[^\n]*", f"evaluationFrequency     {EVAL[R]};")
    rep(r"(   useMemOnlyBuoyancy\s+true;[^\n]*\n)", r"\1" + f"\n   logDensityColumn              true;\n   densityColumnBaseFolder       density-column;\n   densityColumnX                {6*R};\n   densityColumnY                {6*R};\n   logDensityColumnStartStep     {w0};\n   logDensityColumnEndStep       {w1};\n")
    hdr = (f"// pinres_sphere_R{R}_gas.prm -- generated by gen_pinned_resolution_scan.py (do not hand-edit)\n"
           f"// [Claude, 2026-09-28] FULLY PINNED sphere r={8*R} at z={zc} (nominal 0.75 submerged, waterline {wl:.3f} = {FACTOR:.4f} x avgD {AVG_D[R]}), still water,\n"
           f"// R={R} resolution level of the R1/R2/R4 family (true g_SI, see the original prm's header below), {T} steps; force log every {EVAL[R]} steps,\n"
           f"// density column x=y={6*R} over steps {w0}-{w1}. Derived from buoyancy_compare_sphere_r{R}_mem_gas.prm.\n// ---- original header follows ----\n")
    return hdr + t
def sbatch(R):
    big = R == 4
    part = "#SBATCH --partition=multinode\n#SBATCH --nodes=8\n#SBATCH --ntasks=576\n#SBATCH --time=03:00:00" if big else f"#SBATCH --partition=singlenode\n#SBATCH --nodes=1\n#SBATCH --ntasks=72\n#SBATCH --time={'01:30:00' if R == 2 else '01:00:00'}"
    npr = 576 if big else 72
    return f"""#!/bin/bash -l
#SBATCH --job-name=antidunes-pinres-sphere-R{R}
{part}
#SBATCH --output=sbatch-output/output/pinres_sphere_R{R}_%j.out
#SBATCH --error=sbatch-output/error/pinres_sphere_R{R}_%j.err
#SBATCH --mail-type=END,FAIL
#SBATCH --mail-user=dennys.huber@fau.de

# [Claude, 2026-09-28] Pinned-sphere RESOLUTION scan, R={R} (see gen_pinned_resolution_scan.py). Submit as
# `cd <checkout>/apps/showcases/Antidunes && sbatch jobs/run_{npr}_pinres_sphere_R{R}.sbatch`. Needs spheres_out_buoyancy_r{R}.dat in the build dir.
# Results (per-job dir, never overwritten, read-only backup in ~/pinscan_backup, no vault archive -- its file quota is exhausted).
if [[ -n "${{SLURM_SUBMIT_DIR:-}}" ]]; then
    REPO="$(cd "$SLURM_SUBMIT_DIR/../../.." && pwd)"
else
    SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
    REPO="$(cd "$SCRIPT_DIR/../../../.." && pwd)"
fi
BIN_DIR="$REPO/build/apps/showcases/Antidunes"
SH="$REPO/apps/showcases/Antidunes/antidunes.sh"
PRM_DIR="$REPO/apps/showcases/Antidunes/prms"
OUT="$REPO/apps/showcases/Antidunes/pinscan_results/${{SLURM_JOB_ID:-manual_$(date +%Y%m%d_%H%M%S)}}"
mkdir -p "$(dirname "$OUT")"
mkdir "$OUT" || {{ echo "results dir $OUT already exists -- refusing to overwrite"; exit 1; }}
BACKUP="$HOME/pinscan_backup/$(basename "$OUT")_pinres_R{R}"
[[ -f "$BIN_DIR/spheres_out_buoyancy_r{R}.dat" ]] || {{ echo "missing bed file spheres_out_buoyancy_r{R}.dat"; exit 1; }}

"$SH" --build --jobs "$(nproc)"

L=R{R}_pinres
rm -rf "$BIN_DIR/density-column" "$BIN_DIR/eval" "$BIN_DIR/vtk-out" "$BIN_DIR/snapshots"
TMPLOG="$OUT/$L.fulllog.tmp"
"$SH" --run --np {npr} --prm "$PRM_DIR/pinres_sphere_R{R}_gas.prm" > "$TMPLOG" 2>&1
echo "exit=$?" > "$OUT/$L.status"
grep "\\[FloaterForces\\]" "$TMPLOG" | cut -c1-420 > "$OUT/$L.forces.txt"
grep -E "Assertion|FATAL" "$TMPLOG" | head -5 >> "$OUT/$L.status"
cat "$BIN_DIR"/density-column/rank_*.csv 2>/dev/null | awk -F, '$1 ~ /^[0-9]+$/ {{ s[$1]+=$8; r[$5]+=$7; c[$5]++ }} END {{ for (k in s) {{ n++; t+=s[k] }} if (n) printf "waterline_mean %.5f nsteps %d\\n", t/n, n; for (z in r) printf "rho %s %.6f\\n", z, r[z]/c[z] }}' | sort -k1,1 -k2,2n > "$OUT/$L.column.txt"
cp "$BIN_DIR/eval/computedParams.txt" "$OUT/$L.computedParams.txt" 2>/dev/null
rm -f "$TMPLOG"
rm -rf "$BIN_DIR/density-column" "$BIN_DIR/eval" "$BIN_DIR/vtk-out" "$BIN_DIR/snapshots"
mkdir -p "$BACKUP" && cp -n "$OUT"/* "$BACKUP"/ && chmod -R a-w "$OUT" "$BACKUP"
echo "## DONE. Results in $OUT (backup: $BACKUP)"
"""
if __name__ == "__main__":
    for R in (1, 2, 4):
        open(f"prms/pinres_sphere_R{R}_gas.prm", "w", encoding="utf-8").write(prm(R))
        open(f"jobs/run_{576 if R == 4 else 72}_pinres_sphere_R{R}.sbatch", "w", encoding="utf-8").write(sbatch(R))
        print(f"R={R}: zc={zc_for(R)[0]} waterline={zc_for(R)[1]:.3f} steps={STEPS[R]}")
