#!/usr/bin/env python3
"""Pinned-BOX heel-angle scan at REAL gravity (THESIS_PLAN.md 1a, 2026-09-28): tests whether the ~0.3-cell pressure-zero offset at the free
surface explains the cuboid heel-angle error at rho=0.75 (Bogner: stable heel 26.565 deg for rho 0.25 and 0.75, 45 for 0.5).
A single s x 2s x s box (30 x 60 x 30, s=30, roll about Y) is FULLY PINNED (position and rotation) at a fixed heel angle in still water, real
g_SI=9.81 (g_LU 5.06585e-5), R3 domain <96,135,120>, heave chosen so the submerged cross-section area = rho*s^2 at level 60.2. The raw MEM
force and torque_y are logged ([BoxForces]/[BoxTorque], every 250 steps) and compared afterwards with the ideal hydrostatic values at the
MEASURED waterline, with and without the level raised by the measured pressure-zero offset. Ideal torque about the box centre: -F_z*(x_B-x_G).
Generates prms/pinbox_r{RHO}_a{ANGLE}_gas.prm and jobs/run_72_pinbox_scan.sbatch (all cases sequentially in ONE job)."""
import math, re
RHOS = [0.75, 0.25]
ANGLES = [10.0, 20.0, 26.565, 30.0]
S = 30.0; WL0 = 60.2; STEPS = 12000
def tag(a): return "a" + (f"{int(round(a)):02d}" if abs(a - round(a)) < 1e-9 else format(a, "g").replace(".", "p"))
def square(zc, alpha):
    a = math.radians(alpha); c, sn = math.cos(a), math.sin(a); h = S/2
    return [(x*c + z*sn, -x*sn + z*c + zc) for x, z in ((-h, -h), (h, -h), (h, h), (-h, h))]
def clip_below(poly, zw):
    out = []
    for i in range(len(poly)):
        p, q = poly[i], poly[(i+1) % len(poly)]; pin, qin = p[1] <= zw, q[1] <= zw
        if pin: out.append(p)
        if pin != qin:
            t = (zw - p[1])/(q[1] - p[1]); out.append((p[0] + t*(q[0] - p[0]), zw))
    return out
def area(poly):
    return 0.5*sum(poly[i][0]*poly[(i+1) % len(poly)][1] - poly[(i+1) % len(poly)][0]*poly[i][1] for i in range(len(poly))) if len(poly) > 2 else 0.0
def heave(rho, alpha):
    lo, hi = WL0 - 2*S, WL0 + 2*S
    for _ in range(80):
        m = 0.5*(lo+hi)
        lo, hi = (m, hi) if area(clip_below(square(m, alpha), WL0)) > rho*S*S else (lo, m)   # higher centre -> less submerged
    return round(0.5*(lo+hi), 3)
BASE = open("prms/pinscan_sphere_R24_real_f075_gas.prm", encoding="utf-8").read()
def prm(rho, alpha):
    zc = heave(rho, alpha)
    blk = f"""FloatingBoxes
{{
   FloatingBox
   {{
      // fully pinned box, heel {alpha} deg (roll about Y), heave {zc} (submerged area = rho*s^2 at level {WL0})
      position             < 48, 67.5, {zc} >;
      halfExtents          < 15, 30, 15 >;
      densityRatio         {rho};
      settlingSteps        0;
      initialTiltAngleDeg  {alpha};
      comOffsetZ           0;
      pinPosition          true;
      pinAxes              < 1, 1, 1 >;
      pinRotation          true;
      pinRotationAxes      < 1, 1, 1 >;
   }}
}}"""
    t, n = re.subn(r"FloatingSpheres\n\{.*?\n\}\n", blk + "\n", BASE, count=1, flags=re.S); assert n == 1
    hdr = (f"// pinbox_r{int(rho*100):03d}_{tag(alpha)}_gas.prm -- generated by gen_pinned_box_scan.py (do not hand-edit)\n"
           f"// [Claude, 2026-09-28] fully PINNED 30x60x30 box, rho {rho}, heel {alpha} deg, heave {zc}, real g_SI=9.81, {STEPS} steps; density column x=y=5 over 10000-11999.\n"
           f"// Derived from prms/pinscan_sphere_R24_real_f075_gas.prm (sphere block replaced). See gen_pinned_box_scan.py.\n// ---- original header follows ----\n")
    return hdr + t, zc
def sbatch(cases):
    runs = "\n".join(f'run_case "rho{r} heel {a}" pinbox_r{int(r*100):03d}_{tag(a)}_gas.prm box_r{int(r*100):03d}_{tag(a)}' for r, a in cases)
    return f"""#!/bin/bash -l
#SBATCH --job-name=antidunes-pinbox-scan
#SBATCH --partition=singlenode
#SBATCH --nodes=1
#SBATCH --ntasks=72
#SBATCH --time=02:30:00
#SBATCH --output=sbatch-output/output/pinbox_scan_%j.out
#SBATCH --error=sbatch-output/error/pinbox_scan_%j.err
#SBATCH --mail-type=END,FAIL
#SBATCH --mail-user=dennys.huber@fau.de

# [Claude, 2026-09-28] Pinned-box heel-angle scan at real gravity (gen_pinned_box_scan.py): {len(cases)} cases sequentially. Submit as
# `cd <checkout>/apps/showcases/Antidunes && sbatch jobs/run_72_pinbox_scan.sbatch`. Per-job results dir (never overwritten), read-only backup in
# ~/pinscan_backup, NO vault archive (file quota exhausted).
if [[ -n "${{SLURM_SUBMIT_DIR:-}}" ]]; then
    REPO="$(cd "$SLURM_SUBMIT_DIR/../../.." && pwd)"
else
    SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
    REPO="$(cd "$SCRIPT_DIR/../../../.." && pwd)"
fi
BIN_DIR="$REPO/build/apps/showcases/Antidunes"
SH="$REPO/apps/showcases/Antidunes/antidunes.sh"
PRM_DIR="$REPO/apps/showcases/Antidunes/prms"
OUT="$REPO/apps/showcases/Antidunes/pinscan_results/${{SLURM_JOB_ID:-manual_$(date +%Y%m%d_%H%M%S)}}"
mkdir -p "$(dirname "$OUT")"
mkdir "$OUT" || {{ echo "results dir $OUT already exists -- refusing to overwrite"; exit 1; }}
BACKUP="$HOME/pinscan_backup/$(basename "$OUT")_pinbox"

"$SH" --build --jobs "$(nproc)" --bed --bed-np 72

run_case() {{  # $1 banner, $2 prm, $3 label
    echo "## $1"
    rm -rf "$BIN_DIR/density-column" "$BIN_DIR/eval" "$BIN_DIR/vtk-out" "$BIN_DIR/snapshots"
    TMPLOG="$OUT/$3.fulllog.tmp"
    "$SH" --run --np 72 --prm "$PRM_DIR/$2" > "$TMPLOG" 2>&1
    echo "exit=$?" > "$OUT/$3.status"
    grep -E "\\[BoxForces\\]|\\[BoxTorque\\]" "$TMPLOG" | cut -c1-460 > "$OUT/$3.forces.txt"
    grep -E "Assertion|FATAL" "$TMPLOG" | head -5 >> "$OUT/$3.status"
    cat "$BIN_DIR"/density-column/rank_*.csv 2>/dev/null | awk -F, '$1 ~ /^[0-9]+$/ {{ s[$1]+=$8; r[$5]+=$7; c[$5]++ }} END {{ for (k in s) {{ n++; t+=s[k] }} if (n) printf "waterline_mean %.5f nsteps %d\\n", t/n, n; for (z in r) printf "rho %s %.6f\\n", z, r[z]/c[z] }}' | sort -k1,1 -k2,2n > "$OUT/$3.column.txt"
    cp "$BIN_DIR/eval/computedParams.txt" "$OUT/$3.computedParams.txt" 2>/dev/null
    rm -f "$TMPLOG"
    rm -rf "$BIN_DIR/density-column" "$BIN_DIR/eval" "$BIN_DIR/vtk-out" "$BIN_DIR/snapshots"
}}

{runs}

mkdir -p "$BACKUP" && cp -n "$OUT"/* "$BACKUP"/ && chmod -R a-w "$OUT" "$BACKUP"
echo "## DONE. Results in $OUT (backup: $BACKUP)"
"""
if __name__ == "__main__":
    cases = []
    for r in RHOS:
        for a in ANGLES:
            text, zc = prm(r, a); cases.append((r, a))
            open(f"prms/pinbox_r{int(r*100):03d}_{tag(a)}_gas.prm", "w", encoding="utf-8").write(text)
            print(f"rho {r} heel {a}: heave {zc}")
    open("jobs/run_72_pinbox_scan.sbatch", "w", encoding="utf-8").write(sbatch(cases))
