#!/usr/bin/env python3
"""Add initialTiltAngleDeg 25 to a buoyancy_compare box prm's FloatingBox line (both mem and analytic arms, so the
two methods start from an IDENTICAL initial condition and stay directly comparable).

[Claude, 2026-09-22] Root cause (THESIS_PLAN.md, 'TIE TEST' / 'CORRECTION of the tie explanation'): the R1 box at
upright (0 deg) sits on a mapping tie -- its face planes pass exactly through cell centres, and depending on which
way the tie resolves, the mapped bottom layer can end up flush on the floor with no fluid cell underneath, starving
MEM-only buoyancy of the pressure it needs from below. A 25 deg initial tilt (proven once, job 4232331, R1/box/MEM
only, box_mem_tilted25_hypothesis_test_20260914: rises 41.5 -> 56.1 over 2590 steps) breaks every face-alignment tie
at once. This script generates the tilted25 sibling for EVERY box prm (R1/R2/R4 x mem/analytic) -- the analytic arm
never had the tie problem, but is tilted too so mem and analytic are still directly comparable (same initial box
orientation), not just individually fixed.

usage: gen_buoyancy_tilted25_box_prm.py   (no args; regenerates all 6 from prms/buoyancy_compare_box_r{1,2,4}_{mem,analytic}_gas.prm)
"""
import pathlib, re
D = pathlib.Path(__file__).parent / "prms"
for R in (1, 2, 4):
    for method in ("mem", "analytic"):
        src = D / f"buoyancy_compare_box_r{R}_{method}_gas.prm"
        t = src.read_text()
        t2, n = re.subn(r"(FloatingBox \{ position <[^>]*>; halfExtents <[^>]*>; densityRatio [^;]*; settlingSteps [^;]*;) \}",
                        r"\1 initialTiltAngleDeg 25; }", t, count=1)
        assert n == 1, src
        hdr = (f"// buoyancy_compare_box_r{R}_{method}_tilted25_gas.prm   (GENERATED by gen_buoyancy_tilted25_box_prm.py from {src.name} -- edit that file/this script, not this file)\n"
               f"// [Claude, 2026-09-22] Same as {src.name} EXCEPT initialTiltAngleDeg=25 (about world Y) on the FloatingBox -- see gen_buoyancy_tilted25_box_prm.py's own header for why (mapping-tie fix).\n")
        out = D / f"buoyancy_compare_box_r{R}_{method}_tilted25_gas.prm"
        out.write_text(hdr + t2)
        print("wrote", out.name)
