#!/usr/bin/env python3
"""Bogner-like FREE floating box at REAL gravity (THESIS_PLAN.md 1a, 2026-09-28), following Bogner 2017 sect. 5.3.3 as closely as the
real-gravity unit system allows: basin <96,45,40> (liquid depth ~20 = half the height, as his 130x40x40 lower-half fill; the box's long axis
36 = 2s in a 45-wide channel leaves ~4.5 cells per side like his 32 in 40), box s=18 (18 x 36 x 18, long axis Y), free heave and X/Y translation,
roll about the long axis only (pinRotationAxes <1,0,1>: pitch and yaw pinned), heel seed 2.86 deg (his) and 5 deg, rho 0.75 and 0.25.
g_SI=9.81 (g_LU 5.06585e-5, valid for X=96 / bedCopiesInX 1). Generates prms/bognerlike_r{075,025}_h{286,500}_gas.prm + jobs/run_72_bognerlike_box.sbatch."""
import math, re
RHOS = [0.75, 0.25]; SEEDS = [2.86, 5.0]; S = 18.0; WL0 = 20.0; STEPS = 100000
def square(zc, alpha):
    a = math.radians(alpha); c, sn = math.cos(a), math.sin(a); h = S/2
    return [(x*c + z*sn, -x*sn + z*c + zc) for x, z in ((-h, -h), (h, -h), (h, h), (-h, h))]
def clip_below(poly, zw):
    out = []
    for i in range(len(poly)):
        p, q = poly[i], poly[(i+1) % len(poly)]; pin, qin = p[1] <= zw, q[1] <= zw
        if pin: out.append(p)
        if pin != qin:
            t = (zw - p[1])/(q[1] - p[1]); out.append((p[0] + t*(q[0] - p[0]), zw))
    return out
def area(poly):
    return 0.5*sum(poly[i][0]*poly[(i+1) % len(poly)][1] - poly[(i+1) % len(poly)][0]*poly[i][1] for i in range(len(poly))) if len(poly) > 2 else 0.0
def heave(rho, alpha):
    lo, hi = WL0 - 2*S, WL0 + 2*S
    for _ in range(80):
        m = 0.5*(lo+hi); lo, hi = (m, hi) if area(clip_below(square(m, alpha), WL0)) > rho*S*S else (lo, m)
    return round(0.5*(lo+hi), 3)
def htag(a): return f"h{int(round(a*100)):03d}"
BASE = open("prms/pinbox_r075_a10_gas.prm", encoding="utf-8").read()
def prm(rho, seed):
    zc = heave(rho, seed); t = BASE
    def rep(pat, new, flags=re.S):
        nonlocal t; t, n = re.subn(pat, new, t, count=1, flags=flags); assert n == 1, pat
    rep(r"cellsPerBlock\s+<[^>]*>;", "cellsPerBlock                 < 16, 15, 10 >;")
    rep(r"domainSize\s+<[^>]*>;", "domainSize         <96, 45, 40>;")
    rep(r"liquidHeightFactor\s+[\d.]+;", "liquidHeightFactor 3.3227;")
    rep(r"bedCopiesInY\s+\d+;[^\n]*", "bedCopiesInY 1;")
    rep(r"timesteps\s+\d+;", f"timesteps              {STEPS};")
    rep(r"evaluationFrequency\s+\d+;", "evaluationFrequency     250;")
    rep(r"densityColumnY\s+[\d.]+;", "densityColumnY                22.5;")
    rep(r"logDensityColumnStartStep\s+\d+;", f"logDensityColumnStartStep     {STEPS-2000};")
    rep(r"logDensityColumnEndStep\s+\d+;", f"logDensityColumnEndStep       {STEPS-1};")
    rep(r"CellBB_filter_0 \{[^}]*\}", "CellBB_filter_0 { min < 0, 22, 0 >;   max < 96, 23, 40 >; }")
    rep(r"CellBB_filter_1 \{[^}]*\}", "CellBB_filter_1 { min < 0, 0, 0 >;    max < 1, 45, 40 >; }")
    rep(r"CellBB_filter_2 \{[^}]*\}", "CellBB_filter_2 { min < 0, 0, 0 >;    max < 96, 45, 40 >; }")
    blk = f"""FloatingBoxes
{{
   FloatingBox
   {{
      // Bogner-like free box: s=18 (18 x 36 x 18), roll about Y only (pitch/yaw pinned), heave + X/Y translation FREE, heel seed {seed} deg
      position             < 48, 22.5, {zc} >;
      halfExtents          < 9, 18, 9 >;
      densityRatio         {rho};
      settlingSteps        0;
      initialTiltAngleDeg  {seed};
      comOffsetZ           0;
      pinPosition          false;
      pinRotation          true;
      pinRotationAxes      < 1, 0, 1 >;
   }}
}}"""
    rep(r"FloatingBoxes\n\{.*?\n\}\n", blk + "\n")
    hdr = (f"// bognerlike_r{int(rho*100):03d}_{htag(seed)}_gas.prm -- generated by gen_bognerlike_box_scan.py (do not hand-edit)\n"
           f"// [Claude, 2026-09-28] Bogner-like FREE box at real g_SI=9.81: basin <96,45,40> (depth ~20), box 18x36x18 rho {rho}, seed heel {seed} deg, heave {zc},\n"
           f"// free heave + X/Y translation, roll about Y only (pinRotationAxes <1,0,1>), {STEPS} steps, force log every 250. Derived from prms/pinbox_r075_a10_gas.prm.\n// ---- original header follows ----\n")
    return hdr + t, zc
def sbatch(cases, depends=""):
    runs = "\n".join(f'run_case "rho{r} seed {s}" bognerlike_r{int(r*100):03d}_{htag(s)}_gas.prm bl_r{int(r*100):03d}_{htag(s)}' for r, s in cases)
    return f"""#!/bin/bash -l
#SBATCH --job-name=antidunes-bognerlike-box
#SBATCH --partition=singlenode
#SBATCH --nodes=1
#SBATCH --ntasks=72
#SBATCH --time=04:00:00
#SBATCH --output=sbatch-output/output/bognerlike_box_%j.out
#SBATCH --error=sbatch-output/error/bognerlike_box_%j.err
#SBATCH --mail-type=END,FAIL
#SBATCH --mail-user=dennys.huber@fau.de

# [Claude, 2026-09-28] Bogner-like free box at real gravity (gen_bognerlike_box_scan.py): {len(cases)} cases sequentially. Submit as
# `cd <checkout>/apps/showcases/Antidunes && sbatch [--dependency=afterany:<job in the same checkout>] jobs/run_72_bognerlike_box.sbatch`.
# Per-job results dir (never overwritten), read-only backup in ~/pinscan_backup, NO vault archive (file quota exhausted).
if [[ -n "${{SLURM_SUBMIT_DIR:-}}" ]]; then
    REPO="$(cd "$SLURM_SUBMIT_DIR/../../.." && pwd)"
else
    SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
    REPO="$(cd "$SCRIPT_DIR/../../../.." && pwd)"
fi
BIN_DIR="$REPO/build/apps/showcases/Antidunes"
SH="$REPO/apps/showcases/Antidunes/antidunes.sh"
PRM_DIR="$REPO/apps/showcases/Antidunes/prms"
OUT="$REPO/apps/showcases/Antidunes/pinscan_results/${{SLURM_JOB_ID:-manual_$(date +%Y%m%d_%H%M%S)}}"
mkdir -p "$(dirname "$OUT")"
mkdir "$OUT" || {{ echo "results dir $OUT already exists -- refusing to overwrite"; exit 1; }}
BACKUP="$HOME/pinscan_backup/$(basename "$OUT")_bognerlike"

"$SH" --build --jobs "$(nproc)" --bed --bed-np 72

run_case() {{  # $1 banner, $2 prm, $3 label
    echo "## $1"
    rm -rf "$BIN_DIR/density-column" "$BIN_DIR/eval" "$BIN_DIR/vtk-out" "$BIN_DIR/snapshots"
    TMPLOG="$OUT/$3.fulllog.tmp"
    "$SH" --run --np 72 --prm "$PRM_DIR/$2" > "$TMPLOG" 2>&1
    echo "exit=$?" > "$OUT/$3.status"
    grep -E "\\[BoxForces\\]|\\[BoxTorque\\]" "$TMPLOG" | cut -c1-460 > "$OUT/$3.forces.txt"
    grep -E "Assertion|FATAL" "$TMPLOG" | head -5 >> "$OUT/$3.status"
    cat "$BIN_DIR"/density-column/rank_*.csv 2>/dev/null | awk -F, '$1 ~ /^[0-9]+$/ {{ s[$1]+=$8; r[$5]+=$7; c[$5]++ }} END {{ for (k in s) {{ n++; t+=s[k] }} if (n) printf "waterline_mean %.5f nsteps %d\\n", t/n, n; for (z in r) printf "rho %s %.6f\\n", z, r[z]/c[z] }}' | sort -k1,1 -k2,2n > "$OUT/$3.column.txt"
    cp "$BIN_DIR/eval/computedParams.txt" "$OUT/$3.computedParams.txt" 2>/dev/null
    rm -f "$TMPLOG"
    rm -rf "$BIN_DIR/density-column" "$BIN_DIR/eval" "$BIN_DIR/vtk-out" "$BIN_DIR/snapshots"
}}

{runs}

mkdir -p "$BACKUP" && cp -n "$OUT"/* "$BACKUP"/ && chmod -R a-w "$OUT" "$BACKUP"
echo "## DONE. Results in $OUT (backup: $BACKUP)"
"""
if __name__ == "__main__":
    cases = []
    for r in RHOS:
        for s in SEEDS:
            text, zc = prm(r, s); cases.append((r, s))
            open(f"prms/bognerlike_r{int(r*100):03d}_{htag(s)}_gas.prm", "w", encoding="utf-8").write(text); print(f"rho {r} seed {s}: heave {zc}")
    open("jobs/run_72_bognerlike_box.sbatch", "w", encoding="utf-8").write(sbatch(cases))
