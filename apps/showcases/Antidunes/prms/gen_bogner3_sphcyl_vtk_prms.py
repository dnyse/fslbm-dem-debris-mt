"""[Claude, 2026-10-07] Sphere and cylinder equilibrium runs of the thesis (4278714 / 4278486 / 4278485 spheres, 4278476 / 4278477 /
4278484 cylinders, prms bogner3_r{075,050,025}_sphere_s32_101k_vtk_gas.prm and bogner3_r{...}_cyl_s32_101k_vtk_freesharedstart_gas.prm)
rerun to 40000 steps with VTK output that can show the floating bodies. The 2026-09-29 runs wrote no floater point data (that writer
followed the snapshot steps only from 2026-10-01 on) and only a fluid slab y 43..47, which the bodies leave as they drift. Each prm is
the thesis prm with three changes: timesteps 40000, the VTK block with the whole domain (192 x 90 x 120 cells, fill_level +
mapped_flag; floater output follows the same steps), and own snapshot folder names. Release position and everything else unchanged.

[Claude, 2026-10-08] velocity added to the writers (per "make sure every of the 9 runs write the velocity of the complete domain"),
and the three cuboid prms bogner3_r{075,050,025}_deep_s32_40k_vtk_gas.prm (cuboid reruns 4313356/4313358/4313357, which wrote only
the slab y 43..47 with velocity + fill_level; those runs were deleted on request) get the same whole-domain VTK block in place:
only their VTK block is replaced, timesteps 40000 and snapshot folders are kept. The script is idempotent."""
import re
from pathlib import Path

P = Path(__file__).resolve().parent
STEPS = "0,250,500,1000,2000,4000,8000,12000,16000,20000,24000,28000,32000,36000,39999"
BLOCK = """   %s
   {
      writeFrequency       %d;
      ghostLayers          0;
      baseFolder           vtk-out;
      samplingResolution   1;
      useMPIIO false;%s
      writers
      {
         velocity;
         fill_level;
         mapped_flag;
      }
      before_functions { gas_cell_zero_setter; }
   }
"""
VTK = ("VTK\n{\n   // [Claude, 2026-10-08] whole domain, velocity + fill_level + mapped_flag, discrete steps up to 40000\n"
       + BLOCK % ("fluid_field", 0, "") + BLOCK % ("fluid_field_snapshots", 1, '\n      steps "%s";' % STEPS)
       + "   domain_decomposition\n   {\n      writeFrequency             0;\n      baseFolder                 vtk-out;\n"
       "      outputDomainDecomposition  true;\n   }\n}\n")
for shape, var in (("sphere", ""), ("cyl", "_freesharedstart")):
    for r in ("075", "050", "025"):
        src = P / f"bogner3_r{r}_{shape}_s32_101k_vtk{var}_gas.prm"
        s = src.read_text()
        i = s.index("\nVTK\n")
        s = s[:i + 1] + VTK
        s, k = re.subn(r"(\n\s*timesteps\s+)101000;", r"\g<1>40000;   // [Claude, 2026-10-07] until equilibrium (thesis run: 101000)", s)
        assert k == 1, src
        s, k = re.subn(r"(\n\s*snapshotBaseFolder\s+)(snapshots_b3_r%s_\w+?)_101k_vtk(\w*);" % r, r"\g<1>\g<2>_40k_vtk\g<3>;", s)
        assert k == 1, src
        hdr = ("// [Claude, 2026-10-07] GENERATED by gen_bogner3_sphcyl_vtk_prms.py: %s (thesis run) with timesteps 40000 and\n"
               "// whole-domain VTK output (velocity, fill_level, mapped_flag, floaters; steps %s); everything else identical.\n" % (src.name, STEPS))
        out = P / f"bogner3_r{r}_{shape}_s32_40k_vtk{var}_gas.prm"
        out.write_text(hdr + s)
        print(out.name)

# [Claude, 2026-10-08] cuboids: replace the slab VTK block of the existing 40k prms in place
MARK = "// [Claude, 2026-10-08] VTK block replaced by gen_bogner3_sphcyl_vtk_prms.py"
for r in ("075", "050", "025"):
    f = P / f"bogner3_r{r}_deep_s32_40k_vtk_gas.prm"
    s = f.read_text()
    i = s.index("\nVTK\n")
    s = s[:i + 1] + VTK
    if MARK not in s:
        s = (MARK + ": whole domain (192 x 90 x 120), velocity + fill_level + mapped_flag,\n"
             "// same steps; was the slab y 43..47 with velocity + fill_level (runs 4313356/4313358/4313357, deleted 2026-10-08).\n" + s)
    f.write_text(s)
    print(f.name)

# [Claude, 2026-10-08] cylinders pinned like the cuboids (per "rerun the cylinders with the same pinning as the cuboids"): the free
# 40k cylinder prm plus pinPosition false / pinRotation true / pinRotationAxes <1,0,1> (rotation about y, the cylinder axis, only),
# own snapshot folder. NOT the set-up of the thesis cylinder runs (4278476/4278477/4278484, fully free).
for r in ("075", "050", "025"):
    src = P / f"bogner3_r{r}_cyl_s32_40k_vtk_freesharedstart_gas.prm"
    s = src.read_text()
    s, k = re.subn(r"(\n(\s*)settlingSteps\s+0;)", r"\1\n\2pinPosition          false;\n\2pinRotation          true;\n"
                   r"\2pinRotationAxes      < 1, 0, 1 >;", s, count=1)
    assert k == 1, src
    s, k = re.subn(r"snapshots_b3_r%s_cyl_s32_40k_vtk_free;" % r, "snapshots_b3_r%s_cyl_s32_40k_vtk_pinned;" % r, s)
    assert k == 1, src
    out = P / f"bogner3_r{r}_cyl_s32_40k_vtk_pinned_gas.prm"
    out.write_text("// [Claude, 2026-10-08] GENERATED by gen_bogner3_sphcyl_vtk_prms.py: %s with the cuboids' rotation pinning\n"
                   "// (pinRotation true, pinRotationAxes <1,0,1>) and its own snapshot folder.\n" % src.name + s)
    print(out.name)
