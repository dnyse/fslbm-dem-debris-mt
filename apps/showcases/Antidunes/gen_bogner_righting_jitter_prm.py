#!/usr/bin/env python3
"""Sub-cell POSITION JITTER variants of the two-box fixed-heel righting-moment scan (s = 16).

    python3 gen_bogner_righting_jitter_prm.py   ->  prms/bogner_righting_jitter_s16_<tag>_gas.prm  (angles x offsets)  + prms/bogner_righting_jitter_s16_manifest.json

Question (THESIS_PLAN.md item 1a): the two-box scan (job 4249061) showed the raw MEM torque of a held box is a static, jagged staircase around the ideal curve (rms 0.14-0.17 LU against an ideal
signal of 0.04-0.19 LU). Is that scatter pure lattice registration (the same geometry shifted by a fraction of a cell gives a different torque)? For four heel angles the two boxes (rho 0.75 / 0.25)
are shifted by dz, dx in {(-0.25,0), (+0.25,0), (0,+0.25), (+0.25,+0.25)} cells (the SAME shift for both boxes), everything else identical to the base run (heel, physics, pins, logging window).
The ideal reference is recomputed at the shifted heave. Base prms: prms/bogner_righting_scan2_s16_<tag>_gas.prm and their manifest.
"""
import json, math, pathlib, re

root = pathlib.Path(__file__).parent / "prms"
base = json.load(open(root / "bogner_righting_scan2_s16_manifest.json"))
s, G, ZW, L_BOX = base["s"], base["g"], base["z_water"], base["box_length"]
BASE_TAGS = ["a25p5", "a26p565", "a29", "a30p5"]
OFFSETS = [(-0.25, 0.0), (0.25, 0.0), (0.0, 0.25), (0.25, 0.25)]      # (dz, dx) in cells, applied to every box

def otag(dz, dx):
    parts = []
    if dz: parts.append(f"z{'m' if dz < 0 else 'p'}{int(round(abs(dz) * 100)):02d}")
    if dx: parts.append(f"x{'m' if dx < 0 else 'p'}{int(round(abs(dx) * 100)):02d}")
    return "_".join(parts)

def square(zc, alpha_deg):
    a = math.radians(alpha_deg); c, sn = math.cos(a), math.sin(a); h = s / 2.0
    return [(x * c + z * sn, -x * sn + z * c + zc) for x, z in ((-h, -h), (h, -h), (h, h), (-h, h))]
def clip_below(poly, zw):
    out = []
    for i in range(len(poly)):
        p, q = poly[i], poly[(i + 1) % len(poly)]; pin, qin = p[1] <= zw, q[1] <= zw
        if pin: out.append(p)
        if pin != qin:
            t = (zw - p[1]) / (q[1] - p[1]); out.append((p[0] + t * (q[0] - p[0]), zw))
    return out
def area_centroid(poly):
    if len(poly) < 3: return 0.0, (0.0, 0.0)
    A = cx = cz = 0.0
    for i in range(len(poly)):
        x0, z0 = poly[i]; x1, z1 = poly[(i + 1) % len(poly)]; cr = x0 * z1 - x1 * z0
        A += cr; cx += (x0 + x1) * cr; cz += (z0 + z1) * cr
    A *= 0.5
    return A, (cx / (6 * A), cz / (6 * A))

runs, cases = [], []
for btag in BASE_TAGS:
    alpha = base["angles"][base["tags"].index(btag)]
    src = (root / f"bogner_righting_scan2_s16_{btag}_gas.prm").read_text()
    for dz, dx in OFFSETS:
        tag = btag + "_" + otag(dz, dx)
        def shift(m):
            x, y, z = float(m.group(1)), m.group(2), float(m.group(3))
            return f"position             < {x + dx:.4f}, {y}, {z + dz:.4f} >;"
        txt, n = re.subn(r"position\s+<\s*([-\d.]+),\s*([-\d.]+),\s*([-\d.]+)\s*>;", shift, src)
        assert n == len(base["densities"]), (btag, n)
        head = (f"// bogner_righting_jitter_s16_{tag}_gas.prm   (GENERATED by gen_bogner_righting_jitter_prm.py -- edit the script, not this file)\n"
                f"// [Claude, 2026-09-20] SUB-CELL JITTER variant of prms/bogner_righting_scan2_s16_{btag}_gas.prm: BOTH boxes shifted by dz={dz:+g}, dx={dx:+g} cells (heel {alpha:g} deg unchanged, everything else identical).\n"
                f"// Purpose: size the pure lattice-registration scatter of the held-box MEM torque (see gen_bogner_righting_jitter_prm.py). NOT RUN YET.\n")
        # drop the original first comment line of the base file (its file name) and prepend ours
        body = "\n".join(txt.split("\n")[1:])
        (root / f"bogner_righting_jitter_s16_{tag}_gas.prm").write_text(head + body)
        runs.append(dict(tag=tag, base_tag=btag, alpha=alpha, dz=dz, dx=dx))
        for rho in base["densities"]:
            b = next(c for c in base["cases"] if c["alpha"] == alpha and c["rho"] == rho)
            zc = b["z_centre"] + dz
            A, (bx, _) = area_centroid(clip_below(square(zc, alpha), ZW)); F = G * A * L_BOX
            cases.append(dict(tag=tag, alpha=alpha, rho=rho, dz=dz, dx=dx, z_centre=zc, area_sub=A, x_B_minus_x_G=bx, F_buoy_ideal=F,
                              M_ideal_signed_xz=F * bx, box_index=base["densities"].index(rho)))
(root / "bogner_righting_jitter_s16_manifest.json").write_text(json.dumps(dict(s=s, g=G, z_water=ZW, box_length=L_BOX, window=base["window"], timesteps=base["timesteps"], densities=base["densities"],
                                                                                 xs=base["xs"], base_tags=BASE_TAGS, offsets=OFFSETS, runs=runs, tags=[r["tag"] for r in runs], cases=cases), indent=1))
print(f"{len(runs)} jitter runs ({len(BASE_TAGS)} angles x {len(OFFSETS)} offsets): {[r['tag'] for r in runs]}")
for r in runs[:4]:
    c = [c for c in cases if c["tag"] == r["tag"]]
    print(f"  {r['tag']}: ideal My = -F*d for rho .75/.25: " + " / ".join(f"{-x['M_ideal_signed_xz']:+.4f}" for x in c) + f"  (Fz {c[0]['F_buoy_ideal']:.4f}/{c[1]['F_buoy_ideal']:.4f})")
